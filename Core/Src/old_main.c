void GenerateTestSignal(void)
{
    float A = 100000.0f;   // amplitude

    for(int i = 0; i < FFT_SIZE; i++)
    {
        float t = (float)i / FS;
        TestBuf[i] = (int32_t)(A * sinf(2.0f * 3.1415926f * 1000.0f * t));
    }
}

void ProcessFFT(int32_t *input)
{
    // convert + remove DC
    float32_t mean = 0;

    for (int i = 0; i < FFT_SIZE; i++)
        mean += input[i];

    mean /= FFT_SIZE;

    for (int i = 0; i < FFT_SIZE; i++)
    {
        fft_input[i] = (float32_t)input[i] - mean;
    }

    // window (Hann)
    for (int i = 0; i < FFT_SIZE; i++)
    {
        float w = 0.5f - 0.5f * cosf(2 * 3.1415926f * i / (FFT_SIZE - 1));
        fft_input[i] *= w;
    }

    // FFT
    arm_rfft_fast_f32(&fft, fft_input, fft_output, 0);

    // magnitude
    arm_cmplx_mag_f32(fft_output, fft_mag, FFT_SIZE/2);

    // print first 20 FFT bins
    printf("FFT:");
    for (int k = 0; k < 10; k++)
    {
    	printf(" %ld", (int32_t)fft_mag[k]);
    }
    printf("\r\n");
}
